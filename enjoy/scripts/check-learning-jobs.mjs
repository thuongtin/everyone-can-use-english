import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdtemp, rm } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { build } from "esbuild";
import { Sequelize } from "sequelize";
import { learningBrief, learningDraft } from "./fixtures/learning-lesson.mjs";

const root = path.resolve(import.meta.dirname, "..");
const temp = await mkdtemp(path.join(root, ".tmp-learning-jobs-"));
let db;
try {
  const output = path.join(temp, "subject.mjs");
  await build({ stdin: { contents: `export { LearningJobs } from './src/main/learning/job-runner'; export { LearningStorage } from './src/main/learning/storage'; export { LearningProfileScope } from './src/main/learning/profile-scope'; export { createLearningModels } from './src/main/db/learning-models'; export { canonicalPayloadHash } from './src/main/learning/candidate';`, resolveDir: root, loader: "ts" }, bundle: true, platform: "node", format: "esm", outfile: output, packages: "external", logLevel: "silent" });
  const { LearningJobs, LearningStorage, LearningProfileScope, createLearningModels, canonicalPayloadHash } = await import(pathToFileURL(output).href);
  db = new Sequelize({ dialect: "sqlite", storage: path.join(temp, "jobs.sqlite"), logging: false });
  const models = createLearningModels(db);
  const migration = await import(pathToFileURL(path.join(root, "src/main/db/migrations/1788701024340-create-learning-studio.js")).href);
  await migration.up({ context: db.getQueryInterface() });
  const mapBriefMigration = await import(pathToFileURL(path.join(root, "src/main/db/migrations/1788789600000-add-learning-map-brief.js")).href);
  await mapBriefMigration.up({ context: db.getQueryInterface() });
  const scope = new LearningProfileScope("profile-a", temp);
  const storage = new LearningStorage({ sequelize: db, models, scope });
  const jobs = new LearningJobs(storage);
  const created = await storage.createLesson({ brief: learningBrief, title: "Test" });
  const lessonId = created.lesson.id;
  const revisionId = created.revision.id;
  const setActiveRevision = (activeRevisionId) => storage.write(async (transaction) => {
    const lesson = await models.LearningLesson.findOne({ where: { id: lessonId, profileId: scope.context.profileId }, transaction });
    await lesson.update({ activeRevisionId }, { transaction });
  });
  const create = (requestKey = randomUUID()) => jobs.create({ resourceType: "lesson", resourceId: lessonId, revisionId, requestKey, stages: [{ key: "story", kind: "text" }, { key: "practice", kind: "exercises" }] });
  const envelope = (job, stage, attempt, payload = learningDraft) => ({ schemaVersion: 1, kind: stage.kind, jobId: job.id, stageId: stage.id, attemptId: attempt.id, expectedRevisionId: revisionId, payload, payloadHash: canonicalPayloadHash(payload) });
  const key = randomUUID();
  const first = await create(key);
  assert.equal((await create(key)).job.id, first.job.id);
  await assert.rejects(create(), { code: "learning_resource_busy" });
  const attempt = await jobs.startAttempt(first.stages[0].id, "test-native");
  await assert.rejects(jobs.startAttempt(first.stages[1].id, "test-native"), { code: "learning_stage_busy" });
  const candidate = envelope(first.job, first.stages[0], attempt);
  let writes = 0;
  const publish = async (candidate, transaction) => {
    writes++;
    const revision = await models.LessonRevision.findOne({ where: { id: revisionId, profileId: scope.context.profileId }, transaction });
    await revision.update({ content: candidate.payload, status: "ready" }, { transaction });
  };
  assert.equal((await jobs.commit(candidate, publish)).duplicate, false);
  assert.equal((await jobs.commit(candidate, publish)).duplicate, true);
  assert.equal(writes, 1);
  await assert.rejects(jobs.commit({ ...candidate, payloadHash: "0".repeat(64) }, publish), { code: "learning_payload_hash_mismatch" });
  const secondAttempt = await jobs.startAttempt(first.stages[1].id, "test-native");
  await jobs.failAttempt(secondAttempt.id, "provider_timeout", true);
  assert.equal((await jobs.get(first.job.id)).stages.find((stage) => stage.id === first.stages[1].id).state, "awaiting_retry");
  await assert.rejects(create(), { code: "learning_resource_busy" });
  const retry = await jobs.startAttempt(first.stages[1].id, "test-native");
  assert.equal(retry.ordinal, 2);
  await assert.rejects(jobs.commit(envelope(first.job, first.stages[1], secondAttempt, { exercises: [] }), publish), { code: "learning_attempt_stale" });
  await jobs.cancel(first.job.id);
  await assert.rejects(jobs.commit(envelope(first.job, first.stages[1], retry, { exercises: [] }), publish), { code: "learning_job_cancelled" });
  assert.equal(writes, 1);
  await assert.rejects(jobs.startAttempt(first.stages[1].id, "test-native"), { code: "learning_job_cancelled" });
  const resumed = await jobs.retryAttempt(first.stages[1].id, "test-native");
  assert.equal(resumed.ordinal, 3);
  await assert.rejects(jobs.commit(envelope(first.job, first.stages[1], retry, { exercises: [] }), publish), { code: "learning_attempt_stale" });
  await jobs.cancel(first.job.id);
  const second = await create();
  const running = await jobs.startAttempt(second.stages[0].id, "test-native");
  assert.equal(await jobs.recoverInterrupted(), 1);
  const recovered = await jobs.get(second.job.id);
  assert.equal(recovered.job.state, "interrupted");
  assert.equal(recovered.stages.find((stage) => stage.id === second.stages[0].id).state, "interrupted");
  assert.equal((await models.StageAttempt.findByPk(running.id)).state, "interrupted");
  await jobs.cancel(second.job.id);
  const third = await create();
  const thirdAttempt = await jobs.startAttempt(third.stages[0].id, "test-native");
  await assert.rejects(jobs.commit(envelope(third.job, third.stages[0], thirdAttempt), async (_candidate, transaction) => {
    const revision = await models.LessonRevision.findOne({ where: { id: revisionId, profileId: scope.context.profileId }, transaction });
    await revision.update({ content: learningDraft }, { transaction });
    throw new Error("disk_failure");
  }), /disk_failure/);
  assert.equal((await jobs.get(third.job.id)).stages.find((stage) => stage.id === third.stages[0].id).state, "running");
  const otherScope = new LearningProfileScope("profile-b", temp);
  const other = new LearningJobs(new LearningStorage({ sequelize: db, models: createLearningModels(db), scope: otherScope }));
  await assert.rejects(other.get(third.job.id), { code: "learning_not_found" });
  await setActiveRevision(randomUUID());
  await assert.rejects(jobs.commit(envelope(third.job, third.stages[0], thirdAttempt), publish), { code: "learning_revision_conflict" });
  await setActiveRevision(revisionId);
  await jobs.failAttempt(thirdAttempt.id, "provider_failed");
  const replacement = await create();
  await assert.rejects(jobs.retryAttempt(third.stages[0].id, "test-native"), { code: "learning_resource_busy" });
  await jobs.cancel(replacement.job.id);
  let now = Date.now();
  const leasedJobs = new LearningJobs(storage, () => now);
  const leased = await create();
  const leasedAttempt = await leasedJobs.startAttempt(leased.stages[0].id, "test-native", 100);
  now += 101;
  await assert.rejects(leasedJobs.commit(envelope(leased.job, leased.stages[0], leasedAttempt), publish), { code: "learning_lease_expired" });
  assert.deepEqual(await leasedJobs.expireLeases(), [leasedAttempt.id]);
  assert.equal((await leasedJobs.get(leased.job.id)).job.state, "interrupted");
  await assert.rejects(create(), { code: "learning_resource_busy" });
  await leasedJobs.cancel(leased.job.id);
  await scope.quiesce();
  await otherScope.quiesce();
  await assert.rejects(jobs.get(third.job.id), { code: "profile_closed" });
  console.log("PASS: learning jobs on real SQLite: idempotency, leases, retry, cancel, late results, recovery, rollback, revision and profile isolation.");
} finally {
  await db?.close();
  await rm(temp, { recursive: true, force: true });
}
